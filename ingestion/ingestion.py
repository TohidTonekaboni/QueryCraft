"""Seed the QueryCraft database.

Waits for the Postgres container, applies schema.sql, then tops up products
and order_items to their targets (skipping any table that is already full)
and creates/updates the read-only role used to run generated SQL.
Safe to re-run or resume after an interruption: products have deterministic
SKUs (ON CONFLICT DO NOTHING) and order_items are generated by row index.

Usage: pip install "psycopg[binary]" python-dotenv && python ingestion.py
"""

import os
import random
import sys
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path

import psycopg
from psycopg import sql
from dotenv import load_dotenv

load_dotenv()

DB = {
    "host": os.getenv("POSTGRES_HOST", "localhost"),
    "port": int(os.getenv("POSTGRES_PORT", "5432")),
    "user": os.environ["POSTGRES_USER"],
    "password": os.environ["POSTGRES_PASSWORD"],
    "dbname": os.environ["POSTGRES_DB"],
}
TARGET_PRODUCTS = int(os.getenv("TARGET_PRODUCTS", "1000"))
TARGET_ORDER_ITEMS = int(os.getenv("TARGET_ORDER_ITEMS", "5000"))
READONLY_USER = os.environ["READONLY_USER"]
READONLY_PASSWORD = os.environ["READONLY_PASSWORD"]
READONLY_TIMEOUT = os.getenv("READONLY_STATEMENT_TIMEOUT", "5s")
WAIT_TIMEOUT = int(os.getenv("DB_WAIT_TIMEOUT", "60"))
BATCH_SIZE = 100

SCHEMA = (Path(__file__).parent / "schema.sql").read_text()

# category -> (price range, product nouns)
CATALOG = {
    "Electronics": ((20, 1500), ["Laptop", "Phone", "Headphones", "Monitor", "Keyboard", "Camera", "Speaker", "Tablet"]),
    "Books": ((5, 60), ["Novel", "Cookbook", "Biography", "Textbook", "Comic", "Atlas", "Dictionary"]),
    "Clothing": ((10, 200), ["T-Shirt", "Jacket", "Jeans", "Sneakers", "Scarf", "Hat", "Sweater"]),
    "Home & Kitchen": ((8, 400), ["Blender", "Lamp", "Kettle", "Pan", "Chair", "Vacuum", "Toaster"]),
    "Sports": ((10, 500), ["Yoga Mat", "Dumbbell", "Football", "Tent", "Bicycle", "Racket", "Helmet"]),
}
ADJECTIVES = ["Classic", "Pro", "Ultra", "Mini", "Eco", "Smart", "Deluxe", "Basic", "Premium", "Compact"]


def connect() -> psycopg.Connection:
    """Retry until Postgres accepts connections (container may still be starting)."""
    deadline = time.monotonic() + WAIT_TIMEOUT
    while True:
        try:
            return psycopg.connect(**DB, connect_timeout=3)
        except psycopg.OperationalError as exc:
            if time.monotonic() > deadline:
                sys.exit(f"Postgres not reachable after {WAIT_TIMEOUT}s: {exc}")
            print("Waiting for Postgres...", flush=True)
            time.sleep(2)


def make_product(index: int, category_ids: dict[str, int], names: list[str]) -> tuple:
    """Deterministic product for a given index (same index -> same row)."""
    rng = random.Random(index)
    category = names[index % len(names)]
    (low, high), nouns = CATALOG[category]
    name = f"{rng.choice(ADJECTIVES)} {rng.choice(nouns)} {index:04d}"
    price = round(rng.uniform(low, high), 2)
    return (f"SKU-{index:05d}", name, category_ids[category], price, rng.randint(0, 500))


def seed_products(conn: psycopg.Connection) -> None:
    for name in CATALOG:
        conn.execute("INSERT INTO categories (name) VALUES (%s) ON CONFLICT (name) DO NOTHING", (name,))
    category_ids = dict(conn.execute("SELECT name, id FROM categories").fetchall())
    names = list(CATALOG)

    existing = conn.execute("SELECT count(*) FROM products").fetchone()[0]
    if existing >= TARGET_PRODUCTS:
        print(f"products already has {existing} rows (target {TARGET_PRODUCTS}); skipping.")
        return

    print(f"products has {existing}/{TARGET_PRODUCTS} rows; ingesting...")
    with conn.cursor() as cur:
        for start in range(1, TARGET_PRODUCTS + 1, BATCH_SIZE):
            stop = min(start + BATCH_SIZE, TARGET_PRODUCTS + 1)
            rows = [make_product(i, category_ids, names) for i in range(start, stop)]
            cur.executemany(
                "INSERT INTO products (sku, name, category_id, price, stock) "
                "VALUES (%s, %s, %s, %s, %s) ON CONFLICT (sku) DO NOTHING",
                rows,
            )
            conn.commit()  # commit per batch so an interrupted run can resume
    print(f"products now has {conn.execute('SELECT count(*) FROM products').fetchone()[0]} rows.")


def make_order_item(index: int, products: list[tuple[int, object]], now: datetime) -> tuple:
    """Deterministic order item for a given index. Cheap products sell more often."""
    rng = random.Random(f"order-{index}")
    weights = [1 / (1 + float(price) / 100) for _, price in products]
    product_id, price = rng.choices(products, weights=weights)[0]
    sold_at = now - timedelta(days=rng.randint(0, 364), seconds=rng.randint(0, 86399))
    return (product_id, rng.choices([1, 2, 3, 4, 5], weights=[50, 25, 12, 8, 5])[0], price, sold_at)


def seed_order_items(conn: psycopg.Connection) -> None:
    existing = conn.execute("SELECT count(*) FROM order_items").fetchone()[0]
    if existing >= TARGET_ORDER_ITEMS:
        print(f"order_items already has {existing} rows (target {TARGET_ORDER_ITEMS}); skipping.")
        return

    products = conn.execute("SELECT id, price FROM products ORDER BY id").fetchall()
    if not products:
        print("No products; skipping order_items.")
        return

    print(f"order_items has {existing}/{TARGET_ORDER_ITEMS} rows; ingesting...")
    now = datetime.now(timezone.utc)
    with conn.cursor() as cur:
        # Each batch is one transaction, so existing is always a multiple of completed batches
        # and row index = existing + 1... never repeats an already-inserted index.
        for start in range(existing + 1, TARGET_ORDER_ITEMS + 1, BATCH_SIZE):
            stop = min(start + BATCH_SIZE, TARGET_ORDER_ITEMS + 1)
            rows = [make_order_item(i, products, now) for i in range(start, stop)]
            cur.executemany(
                "INSERT INTO order_items (product_id, quantity, unit_price, sold_at) VALUES (%s, %s, %s, %s)",
                rows,
            )
            conn.commit()
    print(f"order_items now has {conn.execute('SELECT count(*) FROM order_items').fetchone()[0]} rows.")


def setup_readonly_role(conn: psycopg.Connection) -> None:
    """Create (or update) a SELECT-only role with a statement timeout."""
    user = sql.Identifier(READONLY_USER)
    db = sql.Identifier(DB["dbname"])
    exists = conn.execute("SELECT 1 FROM pg_roles WHERE rolname = %s", (READONLY_USER,)).fetchone()
    verb = "ALTER" if exists else "CREATE"
    conn.execute(
        sql.SQL("{} ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD {}").format(
            sql.SQL(verb), user, sql.Literal(READONLY_PASSWORD)
        )
    )
    conn.execute(sql.SQL("ALTER ROLE {} SET statement_timeout = {}").format(user, sql.Literal(READONLY_TIMEOUT)))
    conn.execute(sql.SQL("ALTER ROLE {} SET default_transaction_read_only = on").format(user))
    conn.execute(sql.SQL("GRANT CONNECT ON DATABASE {} TO {}").format(db, user))
    conn.execute(sql.SQL("GRANT USAGE ON SCHEMA public TO {}").format(user))
    conn.execute(sql.SQL("GRANT SELECT ON ALL TABLES IN SCHEMA public TO {}").format(user))
    conn.execute(sql.SQL("ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO {}").format(user))
    conn.commit()
    print(f"Read-only role '{READONLY_USER}' ready.")


def main() -> None:
    with connect() as conn:
        conn.execute(SCHEMA)
        conn.commit()
        seed_products(conn)
        seed_order_items(conn)
        setup_readonly_role(conn)


if __name__ == "__main__":
    main()
